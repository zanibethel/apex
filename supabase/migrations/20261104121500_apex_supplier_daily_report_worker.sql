-- PR #211: server-only, short-lived dispatch claims for daily email.
-- The caller needs an independent 256-bit worker token. Never expose tokens
-- or the outbox through ordinary application role table grants.
begin;
set local lock_timeout='5s';
set local statement_timeout='30s';
do $preflight$
begin
 if to_regclass('apex_internal.supplier_daily_report_email_outbox') is null
  or to_regclass('apex_internal.supplier_daily_report_email_subscriptions') is null
  or to_regclass('apex_internal.supplier_daily_order_reports') is null
  or (select enabled from apex_internal.private_release_gate where singleton) is distinct from false
 then raise exception 'Supplier email dispatch preflight denied';end if;
end $preflight$;

create table apex_internal.supplier_report_mail_worker_tokens(
 name text primary key check(name='daily_report_sender'),
 token_sha256 text not null check(token_sha256 ~ '^[0-9a-f]{64}$'),
 created_at timestamptz not null default now()
);
alter table apex_internal.supplier_report_mail_worker_tokens enable row level security;
alter table apex_internal.supplier_report_mail_worker_tokens force row level security;
revoke all on apex_internal.supplier_report_mail_worker_tokens
 from public,anon,authenticated;

create function apex_internal.assert_daily_report_worker_token(p_token text)
 returns void language plpgsql stable security invoker
 set search_path=pg_catalog as $fn$
begin
 if p_token is null or length(p_token)<>64
  or p_token !~ '^[0-9a-f]{64}$'
  or not exists(
    select 1 from apex_internal.supplier_report_mail_worker_tokens k
    where k.name='daily_report_sender'
     and k.token_sha256=encode(sha256(convert_to(p_token,'UTF8')),'hex')
  )
 then raise exception 'Worker authorization denied' using errcode='42501';end if;
end $fn$;
revoke all on function apex_internal.assert_daily_report_worker_token(text)
 from public,anon,authenticated;

create function public.claim_supplier_daily_report_emails(
 p_worker_token text,p_limit integer default 10
) returns jsonb language plpgsql volatile security definer
 set search_path=pg_catalog as $fn$
declare
 v_day date:=(now() at time zone 'America/Chicago')::date-1;
 v_r record;
 v_outbox apex_internal.supplier_daily_report_email_outbox%rowtype;
 v_items jsonb:='[]'::jsonb;
 v_i integer:=0;
begin
 perform apex_internal.assert_daily_report_worker_token(p_worker_token);
 if p_limit is null or p_limit<1 or p_limit>20
 then raise exception 'Invalid dispatch batch' using errcode='22023';end if;
 -- Never send before a verified snapshot is generated by the daily 10 UTC job.
 for v_r in
  select r.store_id,r.report_date,r.recorded_order_count,
   r.pending_order_count,r.confirmed_order_count,r.refunded_order_count,
   r.cancelled_order_count,r.pending_gross_cents,r.confirmed_gross_cents,
   r.refunded_gross_cents,r.confirmed_btc_sats,
   u.id as recipient_id,u.email
  from apex_internal.supplier_daily_order_reports r
  join apex_internal.supplier_daily_report_email_subscriptions sub
   on sub.store_id=r.store_id and sub.enabled=true
  join public.stores s on s.id=r.store_id
  join public.supplier_memberships member
   on member.supplier_id=s.supplier_id and member.user_id=sub.user_id
  join auth.users u on u.id=member.user_id
   and u.email_confirmed_at is not null
   and length(btrim(coalesce(u.email,''))) between 3 and 254
   and u.email ~* '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'
  where r.report_date=v_day
  order by r.store_id,u.id
 loop
  exit when v_i>=p_limit;
  insert into apex_internal.supplier_daily_report_email_outbox(
   store_id,report_date,user_id)
  values(v_r.store_id,v_day,v_r.recipient_id)
  on conflict(store_id,report_date,user_id) do nothing;
  select * into v_outbox
   from apex_internal.supplier_daily_report_email_outbox o
   where o.store_id=v_r.store_id and o.report_date=v_day
     and o.user_id=v_r.recipient_id
   for update skip locked;
  if not found or v_outbox.state='accepted'
   or (v_outbox.lease_expires_at is not null
       and v_outbox.lease_expires_at>now())
   or v_outbox.attempt_count>=10
  then continue;end if;
  update apex_internal.supplier_daily_report_email_outbox
  set lease_expires_at=now()+interval '15 minutes',
   attempt_count=attempt_count+1,updated_at=now()
  where id=v_outbox.id;
  v_items:=v_items||jsonb_build_array(jsonb_build_object(
   'dispatch_id',v_outbox.id,'store_id',v_r.store_id,
   'report_date',v_day,'email',v_r.email,
   'recorded_order_count',v_r.recorded_order_count,
   'pending_order_count',v_r.pending_order_count,
   'confirmed_order_count',v_r.confirmed_order_count,
   'refunded_order_count',v_r.refunded_order_count,
   'cancelled_order_count',v_r.cancelled_order_count,
   'pending_gross_cents',v_r.pending_gross_cents::text,
   'confirmed_gross_cents',v_r.confirmed_gross_cents::text,
   'refunded_gross_cents',v_r.refunded_gross_cents::text,
   'confirmed_btc_sats',v_r.confirmed_btc_sats::text));
  v_i:=v_i+1;
 end loop;
 return jsonb_build_object('schema_version',1,'report_date',v_day,'items',v_items);
end $fn$;
revoke all on function public.claim_supplier_daily_report_emails(text,integer)
 from public,anon,authenticated;
grant execute on function public.claim_supplier_daily_report_emails(text,integer)
 to anon;

create function public.accept_supplier_daily_report_email(
 p_worker_token text,p_dispatch_id uuid,p_provider_email_id text
) returns boolean language plpgsql volatile security definer
 set search_path=pg_catalog as $fn$
declare v_count integer;
begin
 perform apex_internal.assert_daily_report_worker_token(p_worker_token);
 if p_dispatch_id is null or p_provider_email_id is null
  or length(btrim(p_provider_email_id)) not between 8 and 128
  or p_provider_email_id !~ '^[A-Za-z0-9_-]{8,128}$'
 then raise exception 'Invalid provider acknowledgement' using errcode='22023';end if;
 update apex_internal.supplier_daily_report_email_outbox
 set state='accepted',provider_email_id=p_provider_email_id,
  lease_expires_at=null,updated_at=now()
 where id=p_dispatch_id and state='claimed'
   and lease_expires_at is not null
   and lease_expires_at>=now();
 get diagnostics v_count=row_count;
 return v_count=1;
end $fn$;
revoke all on function public.accept_supplier_daily_report_email(text,uuid,text)
 from public,anon,authenticated;
grant execute on function public.accept_supplier_daily_report_email(text,uuid,text)
 to anon;

do $postflight$
begin
 if has_table_privilege('anon','apex_internal.supplier_report_mail_worker_tokens','SELECT')
  or has_table_privilege('authenticated','apex_internal.supplier_daily_report_email_outbox','INSERT')
  or not has_function_privilege('anon',
      'public.claim_supplier_daily_report_emails(text,integer)','EXECUTE')
  or has_function_privilege('authenticated',
      'public.claim_supplier_daily_report_emails(text,integer)','EXECUTE')
  or (select enabled from apex_internal.private_release_gate where singleton) is distinct from false
 then raise exception 'Supplier worker postflight denied';end if;
end $postflight$;
commit;