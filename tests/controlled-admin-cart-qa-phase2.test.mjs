import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {
 QA_PRODUCT_ID,QA_PRODUCT_NAME,QA_PRICE_CENTS,QA_AVAILABLE_UNITS,
 buildControlledCartQaReview,
} from "../src/lib/cart/controlled-cart-qa.mjs";
import {changeCartItem,normalizeCartSelections} from "../src/lib/cart/customer-cart.mjs";
const read=p=>readFileSync(p,"utf8");
const id=QA_PRODUCT_ID;
const quote=(quantity,code="")=>buildControlledCartQaReview({
 items:[{product_id:id,quantity}],code,boxSize:"auto",
});
test("admin QA Add to Cart uses real bounded cart quantity mutation and server quote math",()=>{
 const added=changeCartItem([],id,1);
 assert.deepEqual(added,[{product_id:id,quantity:1}]);
 const twice=changeCartItem(added,id,2);
 assert.deepEqual(twice,[{product_id:id,quantity:2}]);
 assert.deepEqual(changeCartItem(twice,id,0),[]);
 assert.deepEqual(normalizeCartSelections(twice),twice);
 assert.equal(QA_PRODUCT_NAME,"QA Fitness Water Bottle (synthetic only)");
 assert.equal(QA_PRICE_CENTS,5999);
 assert.equal(QA_AVAILABLE_UNITS,4);
 const one=quote(1);
 assert.equal(one.ok,true);
 assert.equal(one.status,"stock_observed");
 assert.equal(one.items[0].unitPriceCents,5999);
 assert.equal(one.items[0].lineTotalCents,5999);
 assert.equal(one.items[0].availability,"in_stock");
 assert.equal(one.shippingBoxSize,"small");
 assert.equal(one.shippingCents,1500);
 assert.equal(one.totalCents,7499);
 assert.equal(one.canPlaceOrder,false);
 assert.equal(one.canPay,false);
 const two=quote(2);
 assert.equal(two.items[0].quantity,2);
 assert.equal(two.shippingBoxSize,"small");
 assert.equal(two.totalCents,13498);
});
test("quantity three selects Medium USPS automatically and four crosses the free shipping threshold",()=>{
 const three=quote(3);
 assert.equal(three.ok,true);
 assert.equal(three.shippingBoxSize,"medium");
 assert.equal(three.shippingCents,2580);
 assert.equal(three.merchandiseSubtotalCents,17997);
 assert.equal(three.totalCents,20577);
 assert.equal(three.amountUntilFreeShippingCents,2004);
 const four=quote(4);
 assert.equal(four.ok,true);
 assert.equal(four.shippingBoxSize,"medium");
 assert.equal(four.shippingCents,0);
 assert.equal(four.freeShippingReason,"subtotal_threshold");
 assert.equal(four.totalCents,23996);
 assert.equal(four.canPay,false);
});
test("valid TEST10 and SHIPFREE promotions apply after authoritative line pricing",()=>{
 const ten=quote(3,"TEST10");
 assert.equal(ten.ok,true);
 assert.equal(ten.merchandiseDiscountCents,1800);
 assert.equal(ten.discountedMerchandiseCents,16197);
 assert.equal(ten.shippingBoxSize,"medium");
 assert.equal(ten.shippingCents,2580);
 assert.equal(ten.totalCents,18777);
 const enough=quote(4,"TEST10");
 assert.equal(enough.ok,true);
 assert.equal(enough.merchandiseDiscountCents,2400);
 assert.equal(enough.shippingCents,0);
 assert.equal(enough.totalCents,21596);
 const free=quote(1,"SHIPFREE");
 assert.equal(free.ok,true);
 assert.equal(free.shippingCents,0);
 assert.equal(free.freeShippingReason,"discount_code");
 assert.equal(free.totalCents,5999);
 const bad=quote(1,"BADCODE");
 assert.equal(bad.ok,false);
 assert.equal(bad.reason,"Discount code unavailable");
});
test("server catches insufficient stock, invalid product, fake client money and extra fields",()=>{
 const scarce=quote(5);
 assert.equal(scarce.ok,true);
 assert.equal(scarce.status,"unavailable_stock");
 assert.equal(scarce.items[0].availability,"insufficient_stock");
 assert.equal(scarce.canPlaceOrder,false);
 assert.equal(scarce.canPay,false);
 assert.equal(quote(11).ok,false);
 assert.equal(buildControlledCartQaReview({items:[{product_id:"f4000000-0000-4000-8000-000000000202",quantity:1}]}).ok,false);
 assert.equal(buildControlledCartQaReview({items:[{product_id:id,quantity:1,unit_price_cents:"1"}]}).ok,false);
 assert.equal(buildControlledCartQaReview({items:[{product_id:id,quantity:1}],code:"NOT REAL"}).ok,false);
 assert.equal(buildControlledCartQaReview({items:[{product_id:id,quantity:1}],boxSize:"medium"}).ok,false);
 assert.equal(buildControlledCartQaReview({items:[]}).ok,false);
});
